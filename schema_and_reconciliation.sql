-- Line-Item Charges Table
CREATE TABLE dbo.InvoiceCharges (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    INVOICE_NO NVARCHAR(200),
    CARRIER NVARCHAR(200),
    CHARGE_NAME NVARCHAR(500),
    CURRENCY_TYPE NVARCHAR(20),
    AMOUNT DECIMAL(18, 2),
    DATE_EXTRACTED DATETIME DEFAULT GETDATE()
);

-- Charge Summary Table
CREATE TABLE dbo.InvoiceChargeSummary (
    CARRIER NVARCHAR(200),
    CHARGE_NAME NVARCHAR(500),
    CHARGE_COUNT INT,
    REMARK NVARCHAR(20) NULL
);

-- ChargeMaster Reconciliation Query
DELETE FROM dbo.InvoiceChargeSummary;

INSERT INTO dbo.InvoiceChargeSummary (CARRIER, CHARGE_NAME, CHARGE_COUNT)
SELECT 
    CARRIER,
    LOWER(LTRIM(RTRIM(CHARGE_NAME))) AS CHARGE_NAME,
    COUNT(*) AS CHARGE_COUNT
FROM dbo.InvoiceCharges
WHERE CARRIER IS NOT NULL 
  AND CHARGE_NAME IS NOT NULL
GROUP BY CARRIER, LOWER(LTRIM(RTRIM(CHARGE_NAME)));

UPDATE ICS
SET REMARK = CASE
    WHEN EXISTS (
        SELECT 1 
        FROM ICMS.dbo.ChargeMaster CM
        WHERE LOWER(LTRIM(RTRIM(CM.ChargeName))) = LOWER(LTRIM(RTRIM(ICS.CHARGE_NAME)))
    ) THEN 'EXISTS'
    ELSE 'NEW'
END
FROM dbo.InvoiceChargeSummary ICS;